"""Write the Palettes and Colours sections of Kolors/index.md, plus the swatch images they use.

Run with: python3 -I tools/build_indexes.py
build_palettes.py also runs this after every build, so the entry page follows palette_specs.json.
Only the block between the two markers is rewritten; everything else in index.md is hand-written.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from PIL import Image  # noqa: E402

from library import COLORS_DIR, ROOT, load_colors  # noqa: E402
from render_index import render_index_block  # noqa: E402
from specs import load_specs  # noqa: E402

ENTRY_PAGE = ROOT / "index.md"
BLOCK_START = "<!-- kolors-index:start. Generated by tools/build_indexes.py; edits inside this block are overwritten. -->"
BLOCK_END = "<!-- kolors-index:end -->"
SWATCH_DIR = COLORS_DIR / "swatches"
SWATCH_SIZE = (48, 24)


def write_swatches(library):
    SWATCH_DIR.mkdir(exist_ok=True)
    for color in library.values():
        Image.new("RGB", SWATCH_SIZE, color["hex"]).save(SWATCH_DIR / f"{color['slug']}.png", optimize=True)
    stale = [path for path in SWATCH_DIR.glob("*.png") if path.stem not in library]
    for path in stale:
        path.unlink()
    return len(stale)


def with_block(page, block):
    """Return the page with the generated block replaced, or appended if the page has none yet."""
    generated = f"{BLOCK_START}\n\n{block}\n{BLOCK_END}\n"
    if BLOCK_START not in page:
        return page.rstrip() + "\n\n" + generated
    if page.count(BLOCK_START) != 1 or page.count(BLOCK_END) != 1 or page.index(BLOCK_END) < page.index(BLOCK_START):
        raise ValueError(f"{ENTRY_PAGE} must contain exactly one start marker followed by one end marker")
    before, rest = page.split(BLOCK_START)
    after = rest.split(BLOCK_END, 1)[1].lstrip("\n")
    return before + generated + (("\n" + after) if after else "")


def write_indexes(library, specs):
    if not ENTRY_PAGE.exists():
        raise FileNotFoundError(f"{ENTRY_PAGE} is missing; it holds the hand-written introduction")
    removed = write_swatches(library)
    ENTRY_PAGE.write_text(with_block(ENTRY_PAGE.read_text(), render_index_block(library, specs)))
    print(f"Indexed {len(library)} colours and {len(specs)} palettes in {ENTRY_PAGE.name}; removed {removed} stale swatches.")


def main():
    library = load_colors()
    write_indexes(library, load_specs(library))


if __name__ == "__main__":
    main()
